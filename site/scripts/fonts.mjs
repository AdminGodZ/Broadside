// The site's fonts, cut down to what it uses (astro.config.mjs runs this before
// every dev, build and check). The Fontsource files cover all of Latin, every
// weight and, for Newsreader, every optical size: 300 KB in all. These keep the
// characters the site writes, and only the weights and styles it sets:
//
//   newsreader.woff2         upright, weights 400-600, every optical size
//   newsreader-italic.woff2  italic, weight 400 at caption size (the replay's caption)
//   stencil.css              Saira Stencil One, only the letters of the name, inline (1.3 KB)
//
// The stencil face is small enough to travel inside the page, so the name is
// drawn in it at the first paint, with no request.
import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { join } from "node:path";
import subsetFont from "subset-font";

const SITE = join(import.meta.dirname, "..");
const OUT = join(SITE, "src", "fonts");
const NEWSREADER = join(SITE, "node_modules/@fontsource-variable/newsreader/files/newsreader");
const SAIRA = join(SITE, "node_modules/@fontsource/saira-stencil-one/files/saira-stencil-one-latin-400-normal.woff2");

// Printable ASCII and the punctuation the site uses. A character outside this
// set still shows, in the fallback face; add it here if the text needs it.
let ascii = "";
for (let c = 0x20; c < 0x7f; c++) ascii += String.fromCharCode(c);
const TEXT = `${ascii}–—‘’“”…×•·`; // no ✓: Newsreader has none (the game draws its ticks)
const STENCIL_TEXT = "Broadside";

/** CSS unicode-range for a set of characters, so browsers know what each file covers. */
function unicodeRange(text) {
  const points = [...new Set([...text].map((c) => c.codePointAt(0)))].sort((a, b) => a - b);
  const ranges = [];
  for (const p of points) {
    const last = ranges.at(-1);
    if (last && p === last[1] + 1) last[1] = p;
    else ranges.push([p, p]);
  }
  const hex = (p) => `U+${p.toString(16).toUpperCase()}`;
  return ranges.map(([a, b]) => (a === b ? hex(a) : `${hex(a)}-${b.toString(16).toUpperCase()}`)).join(",");
}
export const UNICODE_RANGE = unicodeRange(TEXT);

export const FILES = {
  normal: join(OUT, "newsreader.woff2"),
  italic: join(OUT, "newsreader-italic.woff2"),
  stencil: join(OUT, "stencil.css"),
};

const mtime = (path) => stat(path).then((s) => s.mtimeMs, () => 0);

/** Writes the subsets, unless they're newer than this script and the Fontsource packages. */
export async function subsetFonts() {
  const sources = [import.meta.filename, `${NEWSREADER}-latin-opsz-normal.woff2`, `${NEWSREADER}-latin-opsz-italic.woff2`, SAIRA];
  const newest = Math.max(...(await Promise.all(sources.map(mtime))));
  const oldest = Math.min(...(await Promise.all(Object.values(FILES).map(mtime))));
  if (oldest > newest) return;

  await mkdir(OUT, { recursive: true });
  const woff2 = (file, text, options) => readFile(file).then((font) => subsetFont(font, text, { targetFormat: "woff2", ...options }));
  const [normal, italic, stencil] = await Promise.all([
    woff2(`${NEWSREADER}-latin-opsz-normal.woff2`, TEXT, { variationAxes: { wght: { min: 400, max: 600 } } }),
    // Italic sets only the caption under the replay (.95rem, regular): one instance of it.
    woff2(`${NEWSREADER}-latin-opsz-italic.woff2`, TEXT, { variationAxes: { wght: 400, opsz: 15 } }),
    // The name is set at 21 px and up, where hinting does nothing: without it, a third the size.
    woff2(SAIRA, STENCIL_TEXT, { noHinting: true, keepFeatures: ["kern"] }),
  ]);
  const face = `@font-face{font-family:"Saira Stencil One";src:url(data:font/woff2;base64,${stencil.toString("base64")}) format("woff2");font-weight:400;font-style:normal;font-display:block;unicode-range:${unicodeRange(STENCIL_TEXT)}}`;
  await Promise.all([
    writeFile(FILES.normal, normal),
    writeFile(FILES.italic, italic),
    writeFile(FILES.stencil, `/* Generated by scripts/fonts.mjs. */\n${face}\n`),
  ]);
}
